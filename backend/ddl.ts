import { z } from "zod";
import type { DdlOp } from "../shared/types";
import { identifier, literal, qi } from "./sql";

// A column type as PostgreSQL prints it with format_type: optional schema, multi-word names,
// typmods and array suffixes. Anything else is refused before reaching the server.
const word = String.raw`(?:"[^"\0]{1,63}"|[A-Za-z_][A-Za-z0-9_$]*)`;
const typePattern = new RegExp(
  String.raw`^${word}(?:\.${word})?` +
    String.raw`(?:\s+(?:varying|precision|with(?:out)?\s+time\s+zone))*` +
    String.raw`(?:\s*\(\s*\d{1,5}(?:\s*,\s*-?\d{1,5})?\s*\))?` +
    String.raw`(?:\s+with(?:out)?\s+time\s+zone)?` +
    String.raw`(?:\s*\[\s*\d*\s*\])*$`,
  "i",
);
export const columnType = z
  .string()
  .trim()
  .min(1, "Type de colonne manquant.")
  .max(200)
  .refine((v) => typePattern.test(v), "Type de colonne invalide.");
// Expressions (DEFAULT, CHECK) are SQL by nature. They are executed with the extended
// protocol, which rejects a second statement smuggled after a semicolon.
const expression = z
  .string()
  .trim()
  .min(1, "Expression vide.")
  .max(4000)
  .refine((v) => !v.includes("\0"), "Expression invalide.");
const schemaName = identifier.refine(
  (v) => !v.startsWith("pg_") && v !== "information_schema",
  "Les schémas système sont en lecture seule.",
);
const columnDef = z
  .object({
    name: identifier,
    type: columnType,
    nullable: z.boolean(),
    default: expression.nullable(),
    identity: z.boolean(),
  })
  .refine(
    (c) => !(c.identity && c.default),
    "Une colonne auto-incrémentée ne peut pas avoir de valeur par défaut.",
  );
const columns = z.array(identifier).min(1, "Choisissez au moins une colonne.");
const fkAction = z.enum([
  "NO ACTION",
  "RESTRICT",
  "CASCADE",
  "SET NULL",
  "SET DEFAULT",
]);
const on = { schema: schemaName, table: identifier };
export const ddlSchema = z.discriminatedUnion("op", [
  z.object({
    ...on,
    op: z.literal("createTable"),
    columns: z.array(columnDef).min(1, "Ajoutez au moins une colonne."),
    primaryKey: z.array(identifier),
  }),
  z.object({ ...on, op: z.literal("renameTable"), newName: identifier }),
  z.object({ ...on, op: z.literal("dropTable") }),
  z.object({ ...on, op: z.literal("setTableOwner"), owner: identifier }),
  z.object({ ...on, op: z.literal("addColumn"), column: columnDef }),
  z.object({ ...on, op: z.literal("dropColumn"), column: identifier }),
  z.object({
    ...on,
    op: z.literal("renameColumn"),
    column: identifier,
    newName: identifier,
  }),
  z.object({
    ...on,
    op: z.literal("setType"),
    column: identifier,
    type: columnType,
  }),
  z.object({
    ...on,
    op: z.literal("setNullable"),
    column: identifier,
    nullable: z.boolean(),
  }),
  z.object({
    ...on,
    op: z.literal("setDefault"),
    column: identifier,
    default: expression.nullable(),
  }),
  z.object({
    ...on,
    op: z.literal("setIdentity"),
    column: identifier,
    identity: z.boolean(),
  }),
  z.object({ ...on, op: z.literal("addPrimaryKey"), columns }),
  z.object({
    ...on,
    op: z.literal("addUnique"),
    columns,
    name: identifier.optional(),
  }),
  z.object({
    ...on,
    op: z.literal("addCheck"),
    expression,
    name: identifier.optional(),
  }),
  z.object({
    ...on,
    op: z.literal("addForeignKey"),
    columns,
    refSchema: identifier,
    refTable: identifier,
    refColumns: columns,
    onDelete: fkAction,
    onUpdate: fkAction,
    name: identifier.optional(),
  }),
  z.object({ ...on, op: z.literal("dropConstraint"), name: identifier }),
  z.object({
    ...on,
    op: z.literal("createIndex"),
    columns,
    unique: z.boolean(),
    name: identifier.optional(),
  }),
  z.object({ ...on, op: z.literal("dropIndex"), name: identifier }),
  z.object({
    ...on,
    op: z.literal("setComment"),
    column: identifier.optional(),
    comment: z.string().max(10000).nullable(),
  }),
]);
const list = (names: string[]) => names.map(qi).join(", ");
const named = (name?: string) => (name ? `CONSTRAINT ${qi(name)} ` : "");
export function columnSql(input: z.infer<typeof columnDef>): string {
  const c = columnDef.parse(input);
  return [
    qi(c.name),
    c.type,
    c.identity ? "GENERATED BY DEFAULT AS IDENTITY" : "",
    c.nullable ? "" : "NOT NULL",
    c.default ? `DEFAULT ${c.default}` : "",
  ]
    .filter(Boolean)
    .join(" ");
}
export function ddlSql(input: DdlOp): string {
  const op = ddlSchema.parse(input);
  const table = `${qi(op.schema)}.${qi(op.table)}`;
  const alter = `ALTER TABLE ${table}`;
  switch (op.op) {
    case "createTable": {
      const pk = op.primaryKey.filter((p) =>
        op.columns.some((c) => c.name === p),
      );
      const parts = op.columns.map((c) => "  " + columnSql(c));
      if (pk.length) parts.push(`  PRIMARY KEY (${list(pk)})`);
      return `CREATE TABLE ${table} (\n${parts.join(",\n")}\n);`;
    }
    case "renameTable":
      return `${alter} RENAME TO ${qi(op.newName)};`;
    case "dropTable":
      return `DROP TABLE ${table} RESTRICT;`;
    case "setTableOwner":
      return `${alter} OWNER TO ${qi(op.owner)};`;
    case "addColumn":
      return `${alter} ADD COLUMN ${columnSql(op.column)};`;
    case "dropColumn":
      return `${alter} DROP COLUMN ${qi(op.column)} RESTRICT;`;
    case "renameColumn":
      return `${alter} RENAME COLUMN ${qi(op.column)} TO ${qi(op.newName)};`;
    case "setType":
      return `${alter} ALTER COLUMN ${qi(op.column)} TYPE ${op.type} USING ${qi(op.column)}::${op.type};`;
    case "setNullable":
      return `${alter} ALTER COLUMN ${qi(op.column)} ${op.nullable ? "DROP" : "SET"} NOT NULL;`;
    case "setDefault":
      return op.default
        ? `${alter} ALTER COLUMN ${qi(op.column)} SET DEFAULT ${op.default};`
        : `${alter} ALTER COLUMN ${qi(op.column)} DROP DEFAULT;`;
    case "setIdentity":
      return op.identity
        ? `${alter} ALTER COLUMN ${qi(op.column)} ADD GENERATED BY DEFAULT AS IDENTITY;`
        : `${alter} ALTER COLUMN ${qi(op.column)} DROP IDENTITY IF EXISTS;`;
    case "addPrimaryKey":
      return `${alter} ADD PRIMARY KEY (${list(op.columns)});`;
    case "addUnique":
      return `${alter} ADD ${named(op.name)}UNIQUE (${list(op.columns)});`;
    case "addCheck":
      return `${alter} ADD ${named(op.name)}CHECK (${op.expression});`;
    case "addForeignKey":
      if (op.columns.length !== op.refColumns.length)
        throw new Error(
          "La clé étrangère doit référencer autant de colonnes qu’elle en contient.",
        );
      return `${alter} ADD ${named(op.name)}FOREIGN KEY (${list(op.columns)}) REFERENCES ${qi(op.refSchema)}.${qi(op.refTable)} (${list(op.refColumns)}) ON DELETE ${op.onDelete} ON UPDATE ${op.onUpdate};`;
    case "dropConstraint":
      return `${alter} DROP CONSTRAINT ${qi(op.name)} RESTRICT;`;
    case "createIndex":
      return `CREATE ${op.unique ? "UNIQUE " : ""}INDEX ${op.name ? qi(op.name) + " " : ""}ON ${table} (${list(op.columns)});`;
    case "dropIndex":
      return `DROP INDEX ${qi(op.schema)}.${qi(op.name)} RESTRICT;`;
    case "setComment":
      return `COMMENT ON ${op.column ? `COLUMN ${table}.${qi(op.column)}` : `TABLE ${table}`} IS ${op.comment ? literal(op.comment) : "NULL"};`;
  }
}
