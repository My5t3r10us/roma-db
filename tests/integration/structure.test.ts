import test from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import * as pg from "../../backend/postgres";
import { qi } from "../../backend/sql";
import type { DdlOp, ProfileInput, Resource } from "../../shared/types";

test("Access matrix and structure editor on the devdb test database", async (t) => {
  const url = new URL(process.env.DATABASE_URL!);
  const database = decodeURIComponent(url.pathname.slice(1));
  assert(
    database.endsWith("_test"),
    "Integration tests must use a devdb _test database.",
  );
  const profile: ProfileInput = {
    id: "integration",
    name: "Test",
    host: url.hostname,
    port: Number(url.port || 5432),
    user: decodeURIComponent(url.username),
    password: decodeURIComponent(url.password),
    maintenanceDb: database,
    ssl: "disable",
    ca: "",
    cert: "",
    color: "#7755df",
  };
  const client = await pg.connect(profile);
  const prefix = "roma_test_" + randomUUID().replaceAll("-", "").slice(0, 10);
  const schema = prefix;
  const group = prefix + "_group";
  const member = prefix + "_member";
  const role = (name: string) => ({
    name,
    login: false,
    superuser: false,
    createDb: false,
    createRole: false,
    inherit: true,
    replication: false,
    bypassRls: false,
    connectionLimit: -1,
  });
  const on = { schema, table: "items" };
  const find = async (name: string): Promise<Resource> => {
    const found = (await pg.resources(client, schema)).find(
      (r) => r.name === name,
    );
    assert(found, name);
    return found;
  };
  try {
    await pg.crud(client, profile, {
      kind: "schema",
      action: "create",
      name: schema,
    });
    for (const name of [group, member])
      await pg.crud(client, profile, {
        kind: "role",
        action: "create",
        name,
        role: role(name),
      });
    await pg.membership(client, profile, {
      role: group,
      member,
      action: "grant",
      admin: false,
      inherit: true,
      set: true,
    });

    await t.test("structure: create a table with identity and primary key", async () => {
      const ops: DdlOp[] = [
        {
          op: "createTable",
          ...on,
          columns: [
            { name: "id", type: "bigint", nullable: false, default: null, identity: true },
            { name: "label", type: "character varying(80)", nullable: true, default: null, identity: false },
            { name: "created_at", type: "timestamp with time zone", nullable: false, default: "now()", identity: false },
          ],
          primaryKey: ["id"],
        },
        {
          op: "createTable",
          schema,
          table: "tags",
          columns: [
            { name: "id", type: "integer", nullable: false, default: null, identity: true },
            { name: "item_id", type: "bigint", nullable: true, default: null, identity: false },
          ],
          primaryKey: ["id"],
        },
      ];
      assert.match(pg.ddlPreview(ops)[0], /GENERATED BY DEFAULT AS IDENTITY/);
      await pg.ddlApply(client, ops);
      const detail = await pg.tableDetail(client, await find("items"));
      assert.deepEqual(
        detail.columns.map((c) => [c.name, c.type, c.nullable, c.identity]),
        [
          ["id", "bigint", false, true],
          ["label", "character varying(80)", true, false],
          ["created_at", "timestamp with time zone", false, false],
        ],
      );
      assert.equal(detail.columns[2].default, "now()");
      assert.equal(detail.constraints[0].type, "primary");
      assert(detail.indexes.some((i) => i.primary && i.constraint));
    });

    await t.test("structure: column, constraint, index and comment edits", async () => {
      await pg.ddlApply(client, [
        { op: "renameColumn", ...on, column: "label", newName: "title" },
        { op: "setType", ...on, column: "title", type: "text" },
        { op: "setNullable", ...on, column: "title", nullable: false },
        { op: "setDefault", ...on, column: "title", default: "'untitled'" },
        { op: "addColumn", ...on, column: { name: "price", type: "numeric(10,2)", nullable: true, default: null, identity: false } },
        { op: "addCheck", ...on, expression: "price >= 0", name: "price_positive" },
        { op: "addUnique", ...on, columns: ["title"], name: "items_title_key" },
        { op: "createIndex", ...on, columns: ["created_at"], unique: false, name: "items_created_idx" },
        { op: "setComment", ...on, comment: "Catalogue d’articles" },
        { op: "setComment", ...on, column: "title", comment: "Nom affiché" },
        {
          op: "addForeignKey",
          schema,
          table: "tags",
          columns: ["item_id"],
          refSchema: schema,
          refTable: "items",
          refColumns: ["id"],
          onDelete: "CASCADE",
          onUpdate: "NO ACTION",
        },
      ]);
      let detail = await pg.tableDetail(client, await find("items"));
      const title = detail.columns.find((c) => c.name === "title")!;
      assert.equal(title.type, "text");
      assert.equal(title.nullable, false);
      assert.equal(title.default, "'untitled'::text");
      assert.equal(title.comment, "Nom affiché");
      assert.equal(detail.comment, "Catalogue d’articles");
      assert(detail.constraints.some((c) => c.type === "check" && c.name === "price_positive"));
      assert(detail.indexes.some((i) => i.name === "items_created_idx" && !i.constraint));
      const tags = await pg.tableDetail(client, await find("tags"));
      const fk = tags.constraints.find((c) => c.type === "foreign")!;
      assert.deepEqual(fk.references, { schema, table: "items", columns: ["id"] });
      assert.deepEqual(fk.columns, ["item_id"]);
      await pg.ddlApply(client, [
        { op: "dropIndex", ...on, name: "items_created_idx" },
        { op: "dropConstraint", ...on, name: "price_positive" },
        { op: "setIdentity", schema, table: "tags", column: "id", identity: false },
        { op: "dropColumn", ...on, column: "price" },
      ]);
      detail = await pg.tableDetail(client, await find("items"));
      assert(!detail.columns.some((c) => c.name === "price"));
      assert(!detail.indexes.some((i) => i.name === "items_created_idx"));
    });

    await t.test("structure: a smuggled statement fails and rolls back the batch", async () => {
      await assert.rejects(
        pg.ddlApply(client, [
          { op: "addColumn", ...on, column: { name: "extra", type: "integer", nullable: true, default: null, identity: false } },
          { op: "setDefault", ...on, column: "title", default: `'x'; DROP TABLE ${qi(schema)}."tags"` },
        ]),
      );
      const detail = await pg.tableDetail(client, await find("items"));
      assert(!detail.columns.some((c) => c.name === "extra"));
      await find("tags");
      assert.throws(() =>
        pg.ddlPreview([{ op: "setType", ...on, column: "title", type: "text; DROP TABLE x" }]),
      );
      assert.throws(() =>
        pg.ddlPreview([{ op: "dropTable", schema: "pg_catalog", table: "pg_class" }]),
      );
    });

    await t.test("matrix fingerprints match access snapshots in every scope", async () => {
      const objects = await pg.matrix(client, profile, "objects", schema);
      const schemas = await pg.matrix(client, profile, "schemas");
      const databases = await pg.matrix(client, profile, "databases");
      for (const entry of [
        ...objects.entries,
        schemas.entries.find((e) => e.resource.name === schema)!,
        databases.entries.find((e) => e.resource.name === database)!,
      ]) {
        const snapshot = await pg.access(client, profile, entry.resource, group);
        assert.equal(entry.fingerprint, snapshot.fingerprint, entry.resource.name);
      }
      assert(objects.roles.includes(group));
      assert.equal(objects.schemaUsage[group], false);
      assert(databases.entries.some((e) => e.grants.some((g) => g.role === "PUBLIC")));
    });

    await t.test("matrix shows direct and inherited access, staged from its fingerprint", async () => {
      let objects = await pg.matrix(client, profile, "objects", schema);
      const items = objects.entries.find((e) => e.resource.name === "items")!;
      await pg.apply(client, profile, database, [
        {
          id: randomUUID(),
          profileId: profile.id,
          database,
          resource: items.resource,
          role: group,
          privilege: "SELECT",
          action: "grant",
          grantOption: false,
          fingerprint: items.fingerprint,
        },
      ]);
      objects = await pg.matrix(client, profile, "objects", schema);
      const after = objects.entries.find((e) => e.resource.name === "items")!;
      assert(after.grants.some((g) => g.role === group && g.privilege === "SELECT"));
      assert.deepEqual(after.effective[group], ["SELECT"]);
      assert.deepEqual(after.effective[member], ["SELECT"]);
      assert(!after.grants.some((g) => g.role === member));
      await assert.rejects(
        pg.apply(client, profile, database, [
          {
            id: randomUUID(),
            profileId: profile.id,
            database,
            resource: items.resource,
            role: group,
            privilege: "INSERT",
            action: "grant",
            grantOption: false,
            fingerprint: items.fingerprint,
          },
        ]),
        /Conflit/,
      );
    });

    await t.test("role previews mask passwords and only send changed attributes", async () => {
      const [sql] = await pg.crudPreview(client, profile, {
        kind: "role",
        action: "update",
        name: member,
        newName: member,
        role: { ...role(member), login: true, password: "secret-value" },
      });
      assert.match(sql, /WITH LOGIN CONNECTION LIMIT -1 PASSWORD '\*{8}'/);
      assert(!sql.includes("secret-value"));
      assert(!sql.includes("SUPERUSER"));
    });
  } finally {
    // Remove only the objects created by this run, never a database or unrelated object.
    await client.query(
      `DROP TABLE IF EXISTS ${qi(schema)}."tags"; DROP TABLE IF EXISTS ${qi(schema)}."items"; DROP SCHEMA IF EXISTS ${qi(schema)} RESTRICT`,
    );
    for (const name of [member, group])
      await pg.crud(client, profile, {
        kind: "role",
        action: "delete",
        name,
        confirmation: name,
      });
    await client.end();
  }
});
